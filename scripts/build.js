// Generates src/generated.js: the calculator list (read from public/) and the admin panel files.
// A Worker has no file system at run time, so this runs before every deploy (npm run deploy does it).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(root, 'public');
const CALC_DIR = path.join(PUBLIC, 'calculators');
const ADMIN_DIR = path.join(root, 'admin');

const decode = (s) => s
  .replace(/<[^>]+>/g, '')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ')
  .replace(/\s+/g, ' ').trim();

// ---- calculators: category + label come from the cards on the home page ----
const files = fs.readdirSync(CALC_DIR).filter((f) => f.endsWith('.html')).sort();
const fromIndex = new Map();
const order = [];
const indexHtml = fs.readFileSync(path.join(PUBLIC, 'index.html'), 'utf8');
{
  const cardRe = /<article class="card">([\s\S]*?)<\/article>/g;
  let m;
  while ((m = cardRe.exec(indexHtml))) {
    const h3 = /<h3>([\s\S]*?)<\/h3>/.exec(m[1]);
    const category = h3 ? decode(h3[1]) : 'Other';
    if (!order.includes(category)) order.push(category);
    const liRe = /<a href="calculators\/([a-z0-9-]+)\.html"[^>]*>([\s\S]*?)<\/a>/g;
    let l;
    while ((l = liRe.exec(m[1]))) if (!fromIndex.has(l[1])) fromIndex.set(l[1], { category, label: decode(l[2]) });
  }
}
const list = files.map((f) => {
  const slug = f.replace(/\.html$/, '');
  const hit = fromIndex.get(slug);
  let label = hit && hit.label;
  if (!label) {
    const head = fs.readFileSync(path.join(CALC_DIR, f), 'utf8').slice(0, 6000);
    const t = /<title>([\s\S]*?)<\/title>/.exec(head);
    if (t) label = decode(t[1]).split(/\s[–|-]\s/)[0];
  }
  return {
    slug,
    title: label || slug.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
    category: hit ? hit.category : 'Other',
    url: '/calculators/' + f,
  };
});
const rank = (c) => { const i = order.indexOf(c); return i === -1 ? 999 : i; };
list.sort((a, b) => rank(a.category) - rank(b.category));

// ---- admin panel files, embedded so only the Worker can serve them ----
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8' };
const admin = {};
for (const f of fs.readdirSync(ADMIN_DIR)) {
  const type = TYPES[path.extname(f)];
  if (type) admin[f] = { type, body: fs.readFileSync(path.join(ADMIN_DIR, f), 'utf8') };
}

const out = `// AUTO-GENERATED by scripts/build.js - do not edit.\nexport const CALCULATORS = ${JSON.stringify(list)};\nexport const ADMIN_FILES = ${JSON.stringify(admin)};\n`;
fs.writeFileSync(path.join(root, 'src', 'generated.js'), out);
console.log(`build: ${list.length} calculators, ${Object.keys(admin).length} admin files -> src/generated.js`);
