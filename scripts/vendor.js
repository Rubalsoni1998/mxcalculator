// Self-host Google Fonts and Chart.js so pages load without third-party requests.
// Usage (needs internet, Node 18+):   node scripts/vendor.js
// What it does:
//   1. downloads Chart.js 4.4.1 -> assets/vendor/chart.umd.js
//   2. downloads the DM Sans / Plus Jakarta Sans / Inter latin woff2 files -> assets/fonts/ and writes assets/css/fonts.css
//   3. rewrites every page: Google Fonts <link> + preconnects -> fonts.css, Chart.js CDN <script> -> local copy
// Safe to run again.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const CHART_URL = process.env.CHART_URL || 'https://cdn.jsdelivr.net/npm/chart.js@4.4.1/dist/chart.umd.js';
const FONTS_CSS_URL = process.env.FONTS_CSS_URL ||
  'https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500;600;700&family=Inter:wght@300;400;500;600;700&family=Plus+Jakarta+Sans:wght@500;600;700;800&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'; // makes Google return woff2

async function get(url, asText) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return asText ? res.text() : Buffer.from(await res.arrayBuffer());
}
const walk = (d, out = []) => {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    if (f.name === 'node_modules' || f.name.startsWith('.')) continue;
    const p = path.join(d, f.name);
    f.isDirectory() ? walk(p, out) : /\.html$/.test(f.name) && out.push(p);
  }
  return out;
};

(async () => {
  fs.mkdirSync(path.join(root, 'assets/vendor'), { recursive: true });
  fs.mkdirSync(path.join(root, 'assets/fonts'), { recursive: true });

  fs.writeFileSync(path.join(root, 'assets/vendor/chart.umd.js'), await get(CHART_URL));
  console.log('Chart.js saved');

  const css = await get(FONTS_CSS_URL, true);
  const blocks = css.match(/(?:\/\*[^*]*\*\/\s*)?@font-face\s*{[^}]*}/g) || [];
  let out = '/* Self-hosted fonts (generated by scripts/vendor.js) */\n', n = 0;
  for (const b of blocks) {
    if (!/\/\*\s*latin\s*\*\//.test(b)) continue;                    // latin subset only
    const family = /font-family:\s*'([^']+)'/.exec(b)[1];
    const weight = /font-weight:\s*([^;]+);/.exec(b)[1].trim();
    const url = /url\(([^)]+\.woff2)\)/.exec(b)[1];
    const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight.replace(/\s+/g, '-')}.woff2`;
    if (!fs.existsSync(path.join(root, 'assets/fonts', file))) fs.writeFileSync(path.join(root, 'assets/fonts', file), await get(url));
    out += `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(../fonts/${file}) format('woff2');}\n`;
    n++;
  }
  if (!n) throw new Error('No latin @font-face blocks found in the Google Fonts response');
  fs.writeFileSync(path.join(root, 'assets/css/fonts.css'), out);
  console.log(`${n} font files saved`);

  let pages = 0;
  for (const f of walk(root)) {
    let h = fs.readFileSync(f, 'utf8'); const o = h;
    const up = path.relative(path.dirname(f), root).split(path.sep).join('/') || '.';
    const prefix = up === '.' ? '' : up + '/';
    h = h.replace(/[ \t]*<link rel="preconnect" href="https:\/\/fonts\.(googleapis|gstatic)\.com"[^>]*>\n?/g, '');
    h = h.replace(/<link href="https:\/\/fonts\.googleapis\.com\/css2[^>]*>/g, `<link rel="stylesheet" href="${prefix}assets/css/fonts.css">`);
    h = h.replace(/https:\/\/cdn\.jsdelivr\.net\/npm\/chart\.js(@[\d.]+)?(\/dist\/chart\.umd\.js)?/g, `${prefix}assets/vendor/chart.umd.js`);
    if (h !== o) { fs.writeFileSync(f, h); pages++; }
  }
  console.log(`Updated ${pages} pages. Third-party font/chart requests are gone.`);
})().catch(e => { console.error('vendor.js failed:', e.message); process.exit(1); });
